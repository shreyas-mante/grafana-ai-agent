-- Portable between PostgreSQL (production) and H2 in PostgreSQL mode (local).

create table workspaces (
    id varchar(40) primary key,
    name varchar(100) not null,
    created_at timestamp not null
);

create table users (
    id varchar(40) primary key,
    email varchar(254) not null unique,
    password_hash varchar(100) not null,
    created_at timestamp not null
);

create table memberships (
    user_id varchar(40) not null references users(id) on delete cascade,
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    role varchar(20) not null,
    created_at timestamp not null,
    primary key (user_id, workspace_id)
);

create table api_keys (
    id varchar(40) primary key,
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    name varchar(100) not null,
    scope varchar(20) not null,
    key_hash varchar(64) not null unique,
    prefix varchar(24) not null,
    allowed_origins varchar(1000),
    created_by varchar(100) not null,
    created_at timestamp not null,
    last_used_at timestamp,
    revoked boolean not null default false
);

create table invites (
    token_hash varchar(64) primary key,
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    role varchar(20) not null,
    created_by varchar(100) not null,
    expires_at timestamp not null,
    used boolean not null default false
);

create table workspace_settings (
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    name varchar(60) not null,
    setting_value text,
    secret boolean not null,
    updated_at timestamp not null,
    primary key (workspace_id, name)
);

create table investigations (
    id varchar(40) primary key,
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    status varchar(20) not null,
    trigger_type varchar(20) not null,
    question varchar(1000) not null,
    service varchar(100),
    lookback_minutes int not null,
    error_group_id varchar(40),
    title varchar(300),
    confidence varchar(20),
    attempts int not null default 0,
    created_at timestamp not null,
    finished_at timestamp,
    data text
);
create index investigations_ws on investigations(workspace_id, created_at);
create index investigations_status on investigations(status, created_at);

create table error_groups (
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    id varchar(40) not null,
    service varchar(100) not null,
    occurrences bigint not null,
    first_seen timestamp not null,
    last_seen timestamp not null,
    data text not null,
    primary key (workspace_id, id)
);
create index error_groups_seen on error_groups(workspace_id, last_seen);

create table kb_docs (
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    id varchar(80) not null,
    title varchar(200) not null,
    type varchar(20) not null,
    source varchar(100) not null,
    content text not null,
    created_at timestamp not null,
    primary key (workspace_id, id)
);

create table schedules (
    id varchar(40) primary key,
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    name varchar(100) not null,
    question varchar(1000) not null,
    service varchar(100),
    interval_minutes int not null,
    enabled boolean not null,
    last_run_at timestamp,
    last_investigation_id varchar(40),
    next_run_at timestamp not null,
    created_at timestamp not null
);

create table actions (
    id varchar(40) primary key,
    workspace_id varchar(40) not null references workspaces(id) on delete cascade,
    investigation_id varchar(40),
    type varchar(40) not null,
    title varchar(300) not null,
    payload text not null,
    reason varchar(2000),
    status varchar(20) not null,
    proposed_at timestamp not null,
    decided_by varchar(100),
    decided_at timestamp,
    result varchar(2000)
);
create index actions_ws on actions(workspace_id, proposed_at);

create table audit_events (
    id bigint generated by default as identity primary key,
    workspace_id varchar(40),
    actor varchar(120) not null,
    action varchar(60) not null,
    detail varchar(2000),
    event_at timestamp not null
);
create index audit_ws on audit_events(workspace_id, event_at);
